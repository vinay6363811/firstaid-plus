/**
 * Translates a complete triage result object into the user's language
 */
function translateResult(result, targetLangCode) {
  if (!result) return result;
  const lang = targetLangCode || 'en-IN';
  if (lang === 'en-IN' || !SUPPORTED_LANGUAGES[lang]) {
    // Return with English UI labels
    return Object.assign({}, result, {
      uiLabels: TRANSLATIONS.ui['en-IN'],
      targetLanguage: SUPPORTED_LANGUAGES['en-IN']
    });
  }

  const guideId = result.id || (result.isUnknownProblem ? 'unknown_problem' : null);
  const localizedGuide = (guideId && TRANSLATIONS.guides[guideId] && TRANSLATIONS.guides[guideId][lang])
    ? TRANSLATIONS.guides[guideId][lang]
    : null;

  const uiLabels = TRANSLATIONS.ui[lang] || TRANSLATIONS.ui['en-IN'];

  // If we have an exact localized guide translation
  if (localizedGuide) {
    return Object.assign({}, result, {
      title: localizedGuide.title || result.title,
      possibleEmergency: localizedGuide.possibleEmergency || result.possibleEmergency,
      whatHappened: localizedGuide.whatHappened || result.whatHappened,
      warningSigns: localizedGuide.warningSigns || result.warningSigns,
      immediateFirstAid: localizedGuide.immediateFirstAid || result.immediateFirstAid,
      whatNotToDo: localizedGuide.whatNotToDo || result.whatNotToDo,
      whenToGetHelp: localizedGuide.whenToGetHelp || result.whenToGetHelp,
      primaryMessage: localizedGuide.primaryMessage || result.primaryMessage,
      secondaryMessage: localizedGuide.secondaryMessage || result.secondaryMessage,
      safetyDisclaimer: uiLabels.disclaimer,
      uiLabels: uiLabels,
      targetLanguage: SUPPORTED_LANGUAGES[lang]
    });
  }

  // If unknown problem
  if (result.isUnknownProblem && TRANSLATIONS.guides.unknown_problem[lang]) {
    const unk = TRANSLATIONS.guides.unknown_problem[lang];
    return Object.assign({}, result, {
      title: unk.title,
      possibleEmergency: unk.possibleEmergency,
      whatHappened: unk.whatHappened,
      primaryMessage: unk.primaryMessage,
      secondaryMessage: unk.secondaryMessage,
      immediateFirstAid: unk.immediateFirstAid,
      whatNotToDo: unk.whatNotToDo,
      whenToGetHelp: unk.whenToGetHelp,
      safetyDisclaimer: uiLabels.disclaimer,
      uiLabels: uiLabels,
      targetLanguage: SUPPORTED_LANGUAGES[lang]
    });
  }

  // Fallback: Return with localized UI labels
  return Object.assign({}, result, {
    safetyDisclaimer: uiLabels.disclaimer,
    uiLabels: uiLabels,
    targetLanguage: SUPPORTED_LANGUAGES[lang]
  });
}

module.exports = {
  SUPPORTED_LANGUAGES,
  detectLanguage,
  INDIC_SYMPTOM_KEYWORDS,
  TRANSLATIONS,
  translateResult
};
